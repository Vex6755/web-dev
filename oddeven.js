let x = 7;
let y = 8;
let z = 9;

// Check x
if (x % 2 === 0) {
  console.log(`x (${x}) is even`);
} else {
  console.log(`x (${x}) is odd`);
}

// Check y
if (y % 2 === 0) {
  console.log(`y (${y}) is even`);
} else {
  console.log(`y (${y}) is odd`);
}

// Check z
if (z % 2 === 0) {
  console.log(`z (${z}) is even`);
} else {
  console.log(`z (${z}) is odd`);
}
